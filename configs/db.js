const mongoose = require('mongoose')
const Role = require('../models/Role')
const Store = require('../models/Store')
const StoreFloor = require('../models/StoreFloor')
const StoreSetting = require('../models/StoreSetting')
const User = require('../models/User')
const { encryptPassword, generateSecurePassword } = require('../helpers/utils')

mongoose.connect(process.env.DATABASE_URL, {
    useNewUrlParser: true,
})
.then(async () => {
    try {
        const totalUser = await User.count()
        if (totalUser > 0) return

        const { preRole } = require('../constants/roleMap')
        let privilege
        let username = 'Admin'
        Object.keys(preRole).forEach(menu => {
            privilege = {
                ...privilege,
                [menu]: {}
            }
            Object.keys(preRole[menu]).forEach(route => {
                privilege[menu][route] = true
            })
        })

        const role = await Role.create({ name: { English: 'Super Admin' }, privilege, description: 'Default role generated by system', isDefault: true })

        const isGenerated = !process.env.DEFAULT_PASSWORD
        const plainPassword = process.env.DEFAULT_PASSWORD || generateSecurePassword(16)
        console.log(isGenerated, plainPassword)
        if (isGenerated) {
            console.warn('==============================================')
            console.warn(`No DEFAULT_PASSWORD set. Generated a one-time password for the "${username}" account:`)
            console.warn(plainPassword)
            console.warn('This is shown only once. Log in and change it immediately.')
            console.warn('==============================================')
        }

        const password = await encryptPassword(plainPassword)
        await User.create({
            username,
            password,
            role: role._id,
            isDefault: true,
            mustChangePassword: true
        })
        await Store.create({})
        await StoreFloor.create({})
        await StoreSetting.create({})
        console.log('Mongo Client is connected...')
    } catch (err) {
        console.error(err)
    }
})
.catch((error) => console.error(error))
